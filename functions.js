// This is one of the most important topics in JavaScript.
// parameter → a, b
// argument  → 10, 20
// return    → sends result back
function add(a, b) {
  return a + b;
}
let result = add(10, 20);
console.log(result);

//  arrow functions:
const add1 = (a, b) => {
  return a + b;
};
result = add1(10, 20);
console.log(result);
